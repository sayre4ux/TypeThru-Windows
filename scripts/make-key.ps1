# Creates or reuses the CNG key pair that signs TypeThru-Windows updates.
# The private key stays in the release signer's user key store; the public key
# is written to src/updatekey.h for the app to verify against.
# A private export lands in .build/update-key-private.txt - back it up somewhere safe.

$ErrorActionPreference = 'Stop'
$keyName = 'TypeThru-Update'
$root = Split-Path -Parent $PSScriptRoot
New-Item -ItemType Directory -Force -Path "$root\.build" | Out-Null

Add-Type -AssemblyName System.Core
$params = New-Object System.Security.Cryptography.CngKeyCreationParameters
$params.ExportPolicy = [System.Security.Cryptography.CngExportPolicies]::AllowPlaintextExport
$params.KeyUsage = [System.Security.Cryptography.CngKeyUsages]::Signing
$params.Provider = [System.Security.Cryptography.CngProvider]::MicrosoftSoftwareKeyStorageProvider

try { $key = [System.Security.Cryptography.CngKey]::Open($keyName) }
catch {
    $key = [System.Security.Cryptography.CngKey]::Create([System.Security.Cryptography.CngAlgorithm]::ECDsaP256, $keyName, $params)
    Write-Host "Created new key '$keyName'."
}
if (($key.ExportPolicy -band [System.Security.Cryptography.CngExportPolicies]::AllowPlaintextExport) -eq 0) {
    throw "Key '$keyName' exists but does not allow export. Delete it (in certmgr or with CngKey::Delete) and rerun."
}

$dsa = [System.Security.Cryptography.ECDsaCng]::new($key)
$public = $dsa.ExportParameters($false)
$private = $dsa.ExportParameters($true)

# BCRYPT_ECCPUBLIC_BLOB for ECDSA P-256: header (magic 0x31534345 -> bytes
# 'E','C','S','1' little-endian, then cbKey = 32 per coordinate) + X(32) + Y(32).
$header = [byte[]](0x45, 0x43, 0x53, 0x31, 32, 0, 0, 0)
$blob = $header + $public.Q.X + $public.Q.Y
$lines = ($blob | ForEach-Object { '0x{0:x2}' -f $_ }) -join ','
@"
// Public key for update signatures; generated by scripts/make-key.ps1. Do not edit by hand.
// ECDSA P-256 over SHA-256, raw r||s signatures (see scripts/sign-update.ps1).
static const unsigned char updateKeyBlob[72] = { $lines };
"@ | Set-Content -Encoding ascii "$root\src\updatekey.h"
Write-Host "Public key written to src\updatekey.h."

$privateText = ($private.D | ForEach-Object { '{0:x2}' -f $_ }) -join ''
@"
TypeThru-Windows update signing key - PRIVATE (D scalar, hex)
Key name: $keyName (CNG user key store of this Windows account)
Recreate with: scripts/make-key.ps1 after deleting the old key.
Backup instruction: store this file somewhere safe and offline. Losing it
means future releases cannot pass in-app updates; leaking it means someone
can sign updates your installed copies trust.
D = $privateText
"@ | Set-Content -Encoding ascii "$root\.build\update-key-private.txt"
Write-Host "Private export written to .build\update-key-private.txt (git-ignored). Back it up."
